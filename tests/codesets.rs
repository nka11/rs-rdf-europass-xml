#![allow(clippy::unwrap_used, clippy::expect_used, clippy::indexing_slicing)]
//! Staleness test for `src/codesets.rs` and its regenerator (DESIGN section 4.9).
//! Regenerate with: cargo test --test codesets -- --ignored regenerate_code_sets
use std::fs;
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

