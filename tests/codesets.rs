/// Minimal line scan: only `xsd:enumeration value=` inside the requested `xsd:simpleType`.
fn scan(xsd: &str, type_name: &str) -> Vec<String> {
    let mut cur: Option<String> = None;
    let mut out = Vec::new();
    let open = "<xsd:simpleType name=\"";
    for line in xsd.lines() {
        if let Some(i) = line.find(open) {
            let rest = &line[i + open.len()..];
            cur = rest.split('"').next().map(|s| s.to_string());
        }
        if line.contains("</xsd:simpleType>") {
            cur = None;
        }
        if cur.as_deref() == Some(type_name) {
            if let Some(i) = line.find("<xsd:enumeration value=\"") {
                let rest = &line[i + "<xsd:enumeration value=\"".len()..];
                if let Some(v) = rest.split('"').next() {
                    out.push(v.to_string());
                }
            }
        }
    }
    out.sort();
    out.dedup();
    out
}

fn generate() -> String {
    let mut s = String::from(
        "//! @generated by `cargo test --test codesets -- --ignored regenerate_code_sets`. Do not edit.\n\
         //! Sorted (byte order) code sets extracted from schema/ (DESIGN section 4.9); search with `binary_search`.\n\n",
    );
    for (name, file, ty, _) in SETS {
        let xsd = fs::read_to_string(root().join("schema").join(file))
            .expect("read xsd: run scripts/fetch-schema.sh first");
        let vals = scan(&xsd, ty);
        s.push_str(&format!("pub static {name}: &[&str] = &[\n"));
        for chunk in vals.chunks(12) {
            let items: Vec<String> = chunk.iter().map(|v| format!("\"{v}\"")).collect();
            s.push_str(&format!("    {},\n", items.join(", ")));
        }
        s.push_str("];\n\n");
    }
    s.trim_end().to_string() + "\n"
}

#[test]
fn counts_match_the_xsd() {
    for (name, file, ty, expected) in SETS {
        let xsd = fs::read_to_string(root().join("schema").join(file))
            .expect("read xsd: run scripts/fetch-schema.sh first");
        assert_eq!(scan(&xsd, ty).len(), *expected, "{name}");
    }
}

#[test]
fn codesets_rs_is_not_stale() {
    let on_disk = fs::read_to_string(root().join("src/codesets.rs")).expect("read src/codesets.rs");
    assert_eq!(
        on_disk,
        generate(),
        "src/codesets.rs is stale: run the ignored regenerate_code_sets test"
    );
}

#[test]
fn compiled_sets_behave() {
    use europass_xml::codesets::*;
    assert!(COUNTRIES.binary_search(&"FR").is_ok());
    assert!(COUNTRIES.binary_search(&"fr").is_err());
    assert!(MOTHER_LANGS.binary_search(&"fr").is_ok());
    assert!(FOREIGN_LANGS.binary_search(&"en").is_ok());
    assert!(ACHIEVEMENT_TITLES.binary_search(&"projects").is_ok());
    assert_eq!(EQF, &["1", "2", "3", "4", "5", "6", "7", "8"]);
    for set in [COUNTRIES, NATIONALITIES, MOTHER_LANGS, FOREIGN_LANGS] {
        assert!(set.windows(2).all(|w| w[0] < w[1]), "sorted and unique");
    }
}

#[test]
#[ignore]
fn regenerate_code_sets() {
    fs::write(root().join("src/codesets.rs"), generate()).expect("write");
}
